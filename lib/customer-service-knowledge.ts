/**
 * 組合為傳送給 Gemini 的知識字串
 */
export function getFormattedKnowledgeBase(): string {
  return LIUSHENG_KNOWLEDGE.map((sec) => {
    const items = sec.items
      .map((it) => `### 【${it.topic}】\n${it.content}`)
      .join("\n\n");
    return `## 【${sec.category}】\n${items}`;
  }).join("\n\n--------------------\n\n");
}
